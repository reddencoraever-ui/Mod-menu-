1. **Install Python** (if you haven't already) from python.org.
2. Save the code into a file ending in `.py`.
3. Open a terminal or command prompt.
4. Change to the folder containing the file, for example:

   ```bash
   cd path/to/your/folder
   ```
5. Run it:

   ```bash
   python dev_menu.py
   ```

   or, on some systems:

   ```bash
   python3 dev_menu.py
   ```

